// ORM 的 CodeFirst 和金标准的连接池会用这些写法，缺一个就整条语句
// 42601 失败，客户端表现为「连得上但用不了」。
func TestIdentityColumn(t *testing.T) {
	d := newTestDB(t)
	s := "s"

	run(t, d, s, `
		CREATE TABLE id_a (
			id      integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
			name    text NOT NULL
		)`)
	run(t, d, s, `
		CREATE TABLE id_b (
			id   bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5),
			v    text
		)`)

	res := run(t, d, s, `INSERT INTO id_a (name) VALUES ('a'), ('b') RETURNING id, name`)
	if len(res[0].Rows) != 2 {
		t.Fatalf("应有 2 行返回，实际 %d", len(res[0].Rows))
	}
	for i, row := range res[0].Rows {
		if got := fmt.Sprint(row[0]); got != fmt.Sprint(i+1) {
			t.Fatalf("第 %d 行的自增 id = %s，期望 %d", i+1, got, i+1)
		}
	}

	// IDENTITY 列不允许显式插入值吗？PostgreSQL 里 GENERATED ALWAYS 会拒绝，
	// BY DEFAULT 会接受。godb 两者都按 BY DEFAULT 处理（一律接受显式值）。
	run(t, d, s, `INSERT INTO id_b (id, v) VALUES (7, 'x')`)
	run(t, d, s, `INSERT INTO id_b (v) VALUES ('y')`)
	res = run(t, d, s, `SELECT id, v FROM id_b ORDER BY id`)
	if len(res[0].Rows) != 2 {
		t.Fatalf("id_b 应有 2 行，实际 %d", len(res[0].Rows))
	}

	// 类型不对要明确报错，而不是建出一张怪表。
	if err := runErr(t, d, s, `CREATE TABLE id_bad (id text GENERATED ALWAYS AS IDENTITY)`); err == nil {
		t.Fatal("text 类型的 IDENTITY 列应当报错")
	}
	// 真正的生成列没实现，报错信息要能看懂。
	if err := runErr(t, d, s, `CREATE TABLE id_gen (a int, b int GENERATED ALWAYS AS (a) STORED)`); err == nil {
		t.Fatal("GENERATED ... AS (expr) STORED 应当报错")
	}
}

// ALTER TABLE ADD COLUMN 也要认 IDENTITY（ORM 加字段时常见）。
func TestIdentityColumnAddColumn(t *testing.T) {
	d := newTestDB(t)
	s := "s"
	run(t, d, s, `CREATE TABLE id_add (name text)`)
	run(t, d, s, `INSERT INTO id_add VALUES ('a'), ('b')`)
	run(t, d, s, `ALTER TABLE id_add ADD COLUMN id integer GENERATED BY DEFAULT AS IDENTITY`)
	res := run(t, d, s, `SELECT id FROM id_add ORDER BY id`)
	if len(res[0].Rows) != 2 {
		t.Fatalf("应有 2 行，实际 %d", len(res[0].Rows))
	}
	if got := fmt.Sprint(res[0].Rows[0][0]); got != "1" {
		t.Fatalf("加列后现有行应回填 1，实际 %s", got)
	}
}

func TestBeginTransactionModes(t *testing.T) {
	d := newTestDB(t)
	s := "s"
	run(t, d, s, `CREATE TABLE tmode (id int)`)

	cases := []string{
		`BEGIN`,
		`BEGIN WORK`,
		`BEGIN TRANSACTION`,
		`BEGIN ISOLATION LEVEL READ COMMITTED`,
		`BEGIN ISOLATION LEVEL READ UNCOMMITTED`,
		`BEGIN ISOLATION LEVEL REPEATABLE READ`,
		`BEGIN ISOLATION LEVEL SERIALIZABLE`,
		`BEGIN TRANSACTION ISOLATION LEVEL SERIALIZABLE, READ ONLY`,
		`BEGIN ISOLATION LEVEL READ COMMITTED, READ WRITE`,
		`BEGIN READ ONLY DEFERRABLE`,
		`BEGIN ISOLATION LEVEL SERIALIZABLE, NOT DEFERRABLE`,
		`START TRANSACTION ISOLATION LEVEL READ COMMITTED`,
		`START TRANSACTION READ ONLY`,
	}
	for _, c := range cases {
		if _, err := d.Exec(d.Session(s), c); err != nil {
			t.Fatalf("%q: %v", c, err)
		}
		run(t, d, s, `INSERT INTO tmode VALUES (1)`)
		if _, err := d.Exec(d.Session(s), `COMMIT`); err != nil {
			t.Fatalf("%q commit: %v", c, err)
		}
	}
	// COMMIT / ROLLBACK 的 AND [NO] CHAIN 也要能吃。
	if _, err := d.Exec(d.Session(s), `BEGIN`); err != nil {
		t.Fatal(err)
	}
	if _, err := d.Exec(d.Session(s), `COMMIT AND NO CHAIN`); err != nil {
		t.Fatal(err)
	}
	if _, err := d.Exec(d.Session(s), `BEGIN`); err != nil {
		t.Fatal(err)
	}
	if _, err := d.Exec(d.Session(s), `ROLLBACK AND CHAIN`); err != nil {
		t.Fatal(err)
	}
	// 事务模式写错了还是要报错，不然拼错的 SQL 会静默通过。
	if err := runErr(t, d, s, `BEGIN ISOLATION LEVEL WHATEVER`); err == nil {
		t.Fatal("非法隔离级别应当报错")
	}
}

