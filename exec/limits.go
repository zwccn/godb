package exec

/* 这个引擎只有两道「按行数」的运行期兜底，集中在这里 —— 它们是一对，
   一个管连接输出、一个管全排序。都放在同一处，是为了以后调阈值时能一眼看全。

   为什么是行数而不是字节：字节更准，但每一行的宽度差着七八倍（4 列 vs 30 列），
   要在热路径里逐行量；行数便宜、可解释，用户也能对照自己表里的行数去估算。
   真要「按内存」得上全库共享预算，那是另一件事（见 docs 里的讨论）。

   为什么只能在运行期兜：没有列统计，优化器手上只有表行数，规划期算不出
   「这条查询会攒多少行」—— 它连 WHERE 之后剩几行都不知道。 */

// maxJoinOutput 是连接输出的行数上限，超了直接报错而不是把内存吃光。
//
// 触发它的多半是「忘了写连接条件」：错误文案先劝你检查 ON。注意它只管
// 输出行数，两侧的物化行数不在这里算 —— 那属于另一个更大的话题。
const maxJoinOutput = 2000000

// maxSortRows 是**全排序**（没有 LIMIT）能缓存的行数上限。
//
// Top-N 不受它约束：`ORDER BY … LIMIT k` 走的是大小为 k 的堆，只占 k 行。
// 也就是说这个上限只挡「真的要把整张表排出来」的查询，而那种查询在网页
// 控制台里几乎没有使用场景 —— 结果渲染不出来，导出也该走 COPY。
//
// 用变量而不是常量：测试要把上限临时改小才跑得动（真跑 200 万行要好几分钟）。
// 除测试外没有第二处写它。
var maxSortRows = 2000000

// maxGroups 是 GROUP BY 能建出多少个分组。
//
// 分组表和前面两道是同一个性质：一张只增不减的哈希表。基数列上 `GROUP BY id`
// 在 1 亿行的表里就是 1 亿个分组，每组一份键 + 每个聚合一个累加器 —— 比排序还重
// （排序只存键，分组还要存状态）。
//
// 和 maxSortRows 一样是变量，原因也一样（测试要改小）。
var maxGroups = 2000000
